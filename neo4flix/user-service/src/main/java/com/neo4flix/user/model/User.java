package com.neo4flix.user.model;

import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import org.springframework.data.neo4j.core.schema.Id;
import org.springframework.data.neo4j.core.schema.Node;

/**
 * A (:User) node. Only the user-service writes these properties.
 * Relationships to other nodes (RATED, FRIEND, IN_WATCHLIST) are written with Cypher,
 * so saving this entity never touches them.
 */
@Node("User")
public class User {

    @Id
    private String id;
    /** Always stored in lower case, unique (see {@code Neo4jSchema}). */
    private String username;
    private String email;
    /** BCrypt hash; the plain password is never stored. */
    private String passwordHash;
    private String displayName;
    private String bio;
    private Set<Role> roles = new HashSet<>();
    private Instant createdAt;
    /** Two-factor authentication: secrets are AES-GCM encrypted (see SecretCipher), never stored in clear. */
    private boolean totpEnabled;
    private String totpSecret;
    /** Secret generated by "setup", waiting for a first valid code before 2FA is switched on. */
    private String pendingTotpSecret;
    /** Last TOTP time step accepted: the same code can never be used twice. */
    private long lastTotpStep;
    /** BCrypt hashes of the one-time recovery codes. */
    private List<String> recoveryCodeHashes = new ArrayList<>();

    protected User() {
    }

    public User(String id, String username, String email, String passwordHash, Set<Role> roles) {
        this.id = id;
        this.username = username;
        this.email = email;
        this.passwordHash = passwordHash;
        this.displayName = username;
        this.roles = new HashSet<>(roles);
        this.createdAt = Instant.now();
    }

    public String getId() { return id; }
    public String getUsername() { return username; }
    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }
    public String getPasswordHash() { return passwordHash; }
    public void setPasswordHash(String passwordHash) { this.passwordHash = passwordHash; }
    public String getDisplayName() { return displayName; }
    public void setDisplayName(String displayName) { this.displayName = displayName; }
    public String getBio() { return bio; }
    public void setBio(String bio) { this.bio = bio; }
    public Set<Role> getRoles() { return roles; }
    public Instant getCreatedAt() { return createdAt; }
    public boolean isTotpEnabled() { return totpEnabled; }
    public void setTotpEnabled(boolean totpEnabled) { this.totpEnabled = totpEnabled; }
    public String getTotpSecret() { return totpSecret; }
    public void setTotpSecret(String totpSecret) { this.totpSecret = totpSecret; }
    public String getPendingTotpSecret() { return pendingTotpSecret; }
    public void setPendingTotpSecret(String pendingTotpSecret) { this.pendingTotpSecret = pendingTotpSecret; }
    public long getLastTotpStep() { return lastTotpStep; }
    public void setLastTotpStep(long lastTotpStep) { this.lastTotpStep = lastTotpStep; }
    public List<String> getRecoveryCodeHashes() { return recoveryCodeHashes; }
    public void setRecoveryCodeHashes(List<String> hashes) { this.recoveryCodeHashes = new ArrayList<>(hashes); }
}
